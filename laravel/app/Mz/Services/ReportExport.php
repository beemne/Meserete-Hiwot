        $o->set('isRemoteEnabled', false);
        $o->set('isFontSubsettingEnabled', true);
        $o->set('chroot', array_map(fn ($p) => str_replace('\\', '/', $p), [base_path(), resource_path(), storage_path()]));
        $fontCacheDir = str_replace('\\', '/', storage_path('app/dompdf'));
        if (! is_dir($fontCacheDir)) @mkdir($fontCacheDir, 0775, true);
        $o->set('fontDir', $fontCacheDir);
        $o->set('fontCache', $fontCacheDir);
        $o->set('tempDir', sys_get_temp_dir());
        $pdf = new Dompdf($o);
        $pdf->loadHtml($html, 'UTF-8');
        $pdf->setPaper('A4', count($spec['tables'][0]['columns'] ?? []) > 7 ? 'landscape' : 'portrait');
        $pdf->render();
        // Page numbers in the footer.
        $canvas = $pdf->getCanvas();
        $canvas->page_text($canvas->get_width() - 90, $canvas->get_height() - 30, 'Page {PAGE_NUM} / {PAGE_COUNT}', null, 8, [0.54, 0.48, 0.49]);
        return (string) $pdf->output();
    }

    public static function formatIntervalPercent(array $r, object $p): string
    {
        $status = $r['status'] ?? '';
        if ($status === 'absent') return '0%';
        if ($status === 'excused') {
            $weight = Settings::permissionPolicy()['weight'];
            return Num::round1($weight * 100) . '%';
        }
        if ($status !== 'present' && $status !== 'late') return '—';
        $elapsed = $r['elapsed_seconds'] ?? null;
        if ($elapsed === null) return '100%';

        $sel = DB::table('holiday_selections')->whereIn('status', ['open', 'review', 'finalized'])->orderByDesc('id')->first();
        if ($sel) {
            $cfg = json_decode((string) $sel->config, true) ?: [];
            $rules = $cfg['attendance_rules']['mezmur'] ?? null;
            if ($rules && ! empty($rules['intervals'])) {
                $sc = Selections::scoreOccurrenceInterval($rules['intervals'], $rules['after_last_percent'] ?? 0, (int) $elapsed, 'present', 0.5);
                return $sc['percent'] . '%';
            }
        }
        return '100%';
    }
