    /**
     * Students' marks over one or several subjects. Wide: one row per student, one column per
     * subject; long: one row per student and subject. A subject the student does not take shows
     * "n/a"; a mark not entered shows "—" (never 0); partly entered subjects say how many are missing.
     */
    private static function educationMarks(array $f): array
    {
        $member = fn ($r) => MemberIds::format($r->member_no ?? null, $r->member_group ?? null);
        $classes = DB::table('edu_classes as c');
        if (! empty($f['class_id'])) $classes->where('c.id', $f['class_id']);
        if (! empty($f['department_id'])) $classes->where('c.department_id', $f['department_id']);
        if (! empty($f['academic_year'])) $classes->where('c.academic_year', $f['academic_year']);
        if (! empty($f['semester'])) $classes->where('c.semester', $f['semester']);
        $classes = $classes->get(['c.id', 'c.name', 'c.academic_year', 'c.semester'])->keyBy('id');
        $courseIds = ! empty($f['course_ids']) ? array_map('intval', explode(',', (string) $f['course_ids'])) : [];
        $subjects = DB::table('edu_courses')->whereIn('class_id', $classes->keys()->all() ?: [0])->when($courseIds, fn ($q) => $q->whereIn('id', $courseIds))->orderBy('class_id')->orderBy('name')->get();
        $statuses = ! empty($f['mark_status']) ? [$f['mark_status']] : null;

        $enr = DB::table('edu_enrollments as e')->join('users as u', 'u.id', '=', 'e.user_id')->whereIn('e.class_id', $classes->keys()->all() ?: [0])->whereNull('u.deleted_at')
            ->select('e.class_id', 'e.program', 'e.stream', 'e.status as enrollment_status', 'u.id as user_id', 'u.full_name', 'u.member_no', 'u.member_group')->orderBy('u.full_name');
        $enrollmentStatus = $f['enrollment_status'] ?? 'active';
        if ($enrollmentStatus !== 'all') $enr->where('e.status', $enrollmentStatus);
        if (! empty($f['study_mode'])) $enr->where('e.program', $f['study_mode']);
        if (! empty($f['stream'])) $enr->where('e.stream', $f['stream']);
        if (! empty($f['student'])) MemberIds::search($enr, $f['student']);
        $students = $enr->limit(self::MAX_ROWS)->get()->all();

        // Per subject: its assessments (max marks) and every mark, keyed by student.
        $per = [];
        foreach ($subjects as $s) {
            $as = DB::table('edu_assessments')->where('course_id', $s->id)->get(['id', 'max_score']);
            $marks = DB::table('edu_scores')->whereIn('assessment_id', $as->pluck('id')->all() ?: [0])->whereNotNull('score')
                ->when($statuses, fn ($q) => $q->whereIn('status', $statuses))->get(['assessment_id', 'user_id', 'score', 'status']);
            $by = [];
            foreach ($marks as $m) $by[(int) $m->user_id][] = $m;
            $roster = array_flip(array_map('intval', Edu::rosterQuery($s)->pluck('u.id')->all()));
            $per[$s->id] = ['subject' => $s, 'count' => count($as), 'max' => (float) $as->sum('max_score'), 'by' => $by, 'roster' => $roster];
        }
        $cell = function (array $p, object $st) {
            if (! isset($p['roster'][(int) $st->user_id]) && ($st->enrollment_status === 'active')) return ['n/a', null, null, null];
            $ms = $p['by'][(int) $st->user_id] ?? [];
            if (! $p['count'] || ! $ms) return ['—', null, $p['count'], null];
            $sum = Num::round1(array_sum(array_map(fn ($m) => (float) $m->score, $ms)));
            $missing = $p['count'] - count($ms);
            $status = implode(', ', array_values(array_unique(array_map(fn ($m) => $m->status, $ms))));
            return [$missing ? "$sum ($missing missing)" : $sum, $sum, $missing, $status];
        };
        $layout = ($f['layout'] ?? 'wide') === 'long' ? 'long' : 'wide';
        $common = [
            ['Student ID', fn ($r) => $r['student_id']], ['Name', 'full_name'], ['Class', 'class_name'], ['Academic year', 'academic_year'], ['Semester', 'semester'],
            ['Study mode', 'program'], ['Stream', 'stream'], ['Enrollment', 'enrollment_status'],
        ];
        $rows = [];
        if ($layout === 'wide') {
            $cols = $common;
            foreach ($per as $id => $p) $cols[] = [$p['subject']->name . ' (/' . Num::round1($p['max']) . ')', fn ($r) => $r["s$id"]];
            foreach ($students as $st) {
                $c = $classes[$st->class_id];
                $row = ['student_id' => $member($st), 'full_name' => $st->full_name, 'class_name' => $c->name, 'academic_year' => $c->academic_year, 'semester' => $c->semester,
                    'program' => $st->program, 'stream' => $st->stream, 'enrollment_status' => $st->enrollment_status];
                foreach ($per as $id => $p) $row["s$id"] = ((int) $p['subject']->class_id === (int) $st->class_id || isset($p['roster'][(int) $st->user_id])) ? $cell($p, $st)[0] : 'n/a';
                $rows[] = $row;
            }
        } else {
            $cols = array_merge($common, [['Subject', 'subject'], ['Code', 'code'], ['Obtained', 'obtained'], ['Max', 'max'], ['Percent', 'percent'], ['Missing assessments', 'missing'], ['Mark status', 'mark_status']]);
            foreach ($students as $st) {
                $c = $classes[$st->class_id];
                foreach ($per as $p) {
                    if ((int) $p['subject']->class_id !== (int) $st->class_id && ! isset($p['roster'][(int) $st->user_id])) continue;
                    [$shown, $sum, $missing, $status] = $cell($p, $st);
                    if ($shown === 'n/a') continue;
                    $rows[] = ['student_id' => $member($st), 'full_name' => $st->full_name, 'class_name' => $c->name, 'academic_year' => $c->academic_year, 'semester' => $c->semester,
                        'program' => $st->program, 'stream' => $st->stream, 'enrollment_status' => $st->enrollment_status,
                        'subject' => $p['subject']->name, 'code' => $p['subject']->code, 'obtained' => $sum ?? '—', 'max' => Num::round1($p['max']),
                        'percent' => $sum !== null && $p['max'] > 0 ? Num::round1($sum / $p['max'] * 100) : '—', 'missing' => $missing ?? '—', 'mark_status' => $status ?? '—'];
                }
            }
        }
        return [
            'title' => 'Student marks report',
            'range' => null,
            'summary' => [['Students', count($students)], ['Subjects', count($subjects)], ['Layout', $layout], ['Marks included', $statuses ? implode(', ', $statuses) : 'all statuses'], ['Missing mark', '— (not 0)']],
            'tables' => [self::table($layout === 'wide' ? 'Marks by student' : 'Marks by student and subject', $cols, $rows)],
        ];
    }

    private static function examReport(array $f): array
    {
        if (empty($f['quiz_id'])) throw ApiError::field('quiz_id', 'REQUIRED');
        $quizId = (int) $f['quiz_id'];
        $quiz = DB::table('edu_quizzes as q')->join('edu_courses as c', 'c.id', '=', 'q.course_id')
            ->where('q.id', $quizId)->select('q.*', 'c.name as course_name')->first();
        if (! $quiz) throw ApiError::notFound('QUIZ_NOT_FOUND', 'Quiz or exam not found');

        $attempts = DB::table('edu_quiz_attempts as a')
            ->join('users as u', 'u.id', '=', 'a.user_id')
            ->where('a.quiz_id', $quizId)
            ->select('a.*', 'u.full_name', 'u.member_no')
            ->orderBy('u.full_name')->orderBy('a.attempt_no')
            ->get();

        $graded = $attempts->where('status', '<>', 'in_progress')->count();
        $totalScores = $attempts->where('status', '<>', 'in_progress')->map(fn ($a) => (float) Num::n($a->auto_score ?? 0) + (float) Num::n($a->manual_score ?? 0));
        $avgScore = $graded > 0 ? Num::round1($totalScores->sum() / $graded) : 0.0;

        $summary = [
            ['Exam', $quiz->title],
            ['Course', $quiz->course_name],
            ['Total participants', $attempts->pluck('user_id')->unique()->count()],
            ['Total attempts', $attempts->count()],
            ['Completed attempts', $graded],
            ['Average score', $avgScore],
        ];

        $tables = [
            self::table('Exam attempts', [
                ['Student', 'full_name'],
                ['Member ID', fn ($r) => $r->member_no ?? '—'],
                ['Attempt #', 'attempt_no'],
                ['Status', 'status'],
                ['Started at', 'started_at'],
                ['Submitted at', 'submitted_at'],
                ['Auto score', fn ($r) => Num::n($r->auto_score)],
                ['Manual score', fn ($r) => Num::n($r->manual_score)],
                ['Total score', fn ($r) => (float) Num::n($r->auto_score ?? 0) + (float) Num::n($r->manual_score ?? 0)],
                ['Needs grading', fn ($r) => $r->needs_grading ? 'Yes' : 'No'],
            ], $attempts->all()),
        ];

        return [
            'title' => 'Exam report: ' . $quiz->title,
            'range' => null,
            'summary' => $summary,
            'tables' => $tables,
        ];
    }

    /** Render + audit. @return array{0:string,1:string,2:string} [bytes, content type, file name] */
    public static function export(array $actx, string $kind, string $format, array $f): array
    {
        $auth = $actx['auth'];
        $spec = self::build($auth, $kind, $f);
        $ref = strtoupper(substr(bin2hex(random_bytes(4)), 0, 8));
        $meta = [
            'reference' => $ref,
            'generated_by' => $auth->fullName,
            'generated_at' => Dates::now(),
            'filters' => array_filter($f, fn ($v) => $v !== null && $v !== '' && $v !== []),
        ];
        // A report may name its own file (e.g. an occurrence: program, date and taker).
        $name = isset($spec['filename']) ? $spec['filename'] . '-' . $ref : $kind . '-' . Dates::todayLocal() . '-' . $ref;
        $out = match ($format) {
            'xlsx' => [self::xlsx($spec, $meta), 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', "$name.xlsx"],
            'csv' => [self::csv($spec), 'text/csv; charset=utf-8', "$name.csv"],
            default => [self::pdf($spec, $meta), 'application/pdf', "$name.pdf"],
        };
        Audit::log($actx, Audit::REPORT_EXPORT, 'report', null, ['kind' => $kind, 'format' => $format, 'reference' => $ref, 'filters' => $meta['filters'], 'rows' => array_sum(array_map(fn ($t) => count($t['rows']), $spec['tables']))], $auth->isSystem);
        return $out;
    }

    private static function periodText(array $spec): ?string
    {
        if (! empty($spec['period_label'])) return $spec['period_label'];
        $r = $spec['range'] ?? null;
        if (! $r) return null;
        return self::ethiopianDate($r['from']) . ' – ' . self::ethiopianDate($r['to']);
    }

    private static function csv(array $spec): string
    {
        $t = $spec['tables'][0] ?? ['columns' => [], 'rows' => []];
        $h = fopen('php://temp', 'r+');
        fputcsv($h, $t['columns'], ',', '"', '');
        foreach ($t['rows'] as $r) fputcsv($h, array_map(fn ($v) => $v ?? '', $r), ',', '"', '');
        rewind($h);
        $csv = (string) stream_get_contents($h);
        fclose($h);
        return "\u{FEFF}" . $csv;
    }

    private static function xlsx(array $spec, array $meta): string
    {
        $summary = [['Report', $spec['title']], ['Reference', $meta['reference']], ['Generated by', $meta['generated_by']], ['Generated', self::ethiopianDate($meta['generated_at']) . ' ' . $meta['generated_at']->setTimezone(Dates::tz())->format('H:i')]];
        if ($p = self::periodText($spec)) $summary[] = ['Period', $p];
        foreach ($meta['filters'] as $k => $v) $summary[] = ["Filter: $k", is_scalar($v) ? (string) $v : json_encode($v, JSON_UNESCAPED_UNICODE)];
        foreach ($spec['summary'] as [$k, $v]) $summary[] = [$k, $v];
        $sheets = ['Summary' => array_merge([['Item', 'Value']], $summary)];
        foreach ($spec['tables'] as $i => $t) {
            $name = mb_substr(preg_replace('/[\[\]\*\?\/\\\\:]/', ' ', $t['title']), 0, 28) ?: 'Sheet' . ($i + 1);
            while (isset($sheets[$name])) $name .= ' ' . ($i + 1);
            $sheets[$name] = array_merge([$t['columns']], $t['rows']);
        }
        return Xlsx::write($sheets, freezeHeader: true);
    }

