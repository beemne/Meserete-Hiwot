    public static function ethiopianDate(mixed $d): string
    {
        $dt = Dates::of($d);
        if (! $dt) return '';
        $local = $dt->setTimezone(Dates::tz());
        $e = Ethiopian::toEthiopian((int) $local->format('Y'), (int) $local->format('n'), (int) $local->format('j'));
        return $e['day'] . ' ' . self::ET_MONTHS[$e['month'] - 1] . ' ' . $e['year'] . ' ዓ.ም.';
    }

    private static function cell(mixed $v): string|int|float|null
    {
        if ($v === null) return null;
        if (is_bool($v)) return $v ? '✓' : '—';
        if (is_int($v) || is_float($v)) return $v;
        // Machine-readable in XLSX / CSV (local time); the PDF shows Ethiopian dates.
        if ($v instanceof \DateTimeInterface) return \DateTimeImmutable::createFromInterface($v)->setTimezone(Dates::tz())->format('Y-m-d H:i');
        if (is_array($v) || is_object($v)) return json_encode($v, JSON_UNESCAPED_UNICODE);
        return (string) $v;
    }

    public static function table(string $title, array $columns, iterable $rows): array
    {
        $out = [];
        foreach ($rows as $r) {
            $r = (array) $r;
            $out[] = array_map(fn ($c) => self::cell($c[1] instanceof \Closure ? ($c[1])($r) : ($r[$c[1]] ?? null)), $columns);
            if (count($out) >= self::MAX_ROWS) break;
        }
        return ['title' => $title, 'columns' => array_column($columns, 0), 'rows' => $out];
    }

    private static function allPages(callable $fetch): array
    {
        $items = [];
        for ($page = 1; $page <= 50 && count($items) < self::MAX_ROWS; $page++) {
            $res = $fetch(['page' => $page, 'limit' => 100, 'offset' => ($page - 1) * 100]);
            $items = array_merge($items, $res['items']);
            if ($page >= ($res['meta']['pages'] ?? 1)) break;
        }
        return $items;
    }

    /** The report described once: title, period, summary, tables. */
    public static function build(AuthContext $auth, string $kind, array $f): array
    {
        $member = fn ($r) => MemberIds::format($r['member_no'] ?? null, $r['member_group'] ?? null);
        switch ($kind) {
            case 'users':
                $d = Reports::users($f);
                $summary = [['Distinct sign-ins', $d['distinct_logins']]];
                foreach ((array) $d['by_status'] as $k => $v) $summary[] = ["Accounts: $k", $v];
                return ['title' => 'Users report', 'range' => $d['range'], 'summary' => $summary,
                    'tables' => [self::table('Registrations per day', [['Day', 'day'], ['Registrations', 'count']], $d['registrations_per_day'])]];
            case 'mezmurs':
                $d = Reports::mezmurs($f);
                $t = fn ($title, $rows) => self::table($title, [['Mezmur', 'title'], ['Count', 'count']], $rows);
                return ['title' => 'Mezmur usage report', 'range' => $d['range'], 'summary' => [],
                    'tables' => [$t('Most viewed', $d['top_viewed']), $t('Most played', $d['top_played']), $t('Most favorited', $d['top_favorited']), $t('Most downloaded', $d['top_downloaded']),
                        self::table('Top searches', [['Search', 'q'], ['Count', 'count']], $d['top_searches'])]];
            case 'attendance':
                if (! empty($f['program_id']) && ! empty($f['date'])) {
                    // One occurrence = one report (recurring programs: one per day), with its session.
                    $pid = (int) $f['program_id'];
                    // The query parser hands dates over as midnight UTC; the occurrence is the calendar day.
                    $f['date'] = $f['date'] instanceof \DateTimeInterface ? $f['date']->format('Y-m-d') : substr((string) $f['date'], 0, 10);
                    $pRow = Attendance::getProgram($pid);
                    $prog = ['title' => $pRow->title];
                    $o = Attendance::resolveOccurrence($pRow, $f['date']);
                    $sess = AttendanceSessions::serialize(AttendanceSessions::of($pRow, $o), $pRow, $o, $auth);
                    $roster = array_map(fn ($r) => (array) $r, self::allPages(fn ($p) => Attendance::roster($pid, ['date' => $f['date']], $p)));
                    $present = count(array_filter($roster, fn ($r) => in_array($r['status'] ?? '', ['present', 'late'], true)));
                    $hm = fn ($d) => $d ? Dates::of($d)?->setTimezone(Dates::tz())->format('H:i') : '—';
                    $taker = $sess['taker']['full_name'] ?? '—';
                    $showScore = $auth->can('attendance.reports') || $auth->can('attendance.override');
                    $showIntervalPct = $auth->can('attendance.reports');
                    $columns = [
                        ['Member', 'full_name'],
                        ['Member ID', fn ($r) => $r['member_id'] ?? $member($r)],
                        ['Classes', fn ($r) => $r['classes'] ?? '—'],
                        ['Status', fn ($r) => ! empty($r['legacy_late']) || ($r['status'] ?? '') === 'late' ? 'present (legacy)' : ($r['status'] ?? '—')],
                        ['Captured at', fn ($r) => $hm($r['attended_at'] ?? null)],
                        ['Minutes after start', fn ($r) => isset($r['elapsed_seconds']) && $r['elapsed_seconds'] !== null ? (string) intdiv((int) $r['elapsed_seconds'], 60) : '—'],
                        ['Interval %', fn ($r) => self::formatIntervalPercent($r, $pRow)],
                        ['Method', fn ($r) => $r['via'] ?? '—'],
                        ['Signature', fn ($r) => ! empty($r['signed']) ? 'signed' : (! empty($r['signature_exempt']) ? 'exempt' : (($r['status'] ?? '') === 'present' && empty($r['legacy']) ? 'missing' : '—'))],
                        ['Sync', fn ($r) => ($r['source'] ?? null) === 'offline' ? 'offline → synced' . (($r['time_source'] ?? null) === 'device' ? ' (device time)' : '') : (($r['source'] ?? null) === 'online' ? 'online' : (! empty($r['legacy']) ? 'legacy' : '—'))],
                        ['Recorded by (Taker)', fn ($r) => $r['recorded_by_name'] ?? '—'],
                        ['Notes', fn ($r) => $r['notes'] ?? '—'],
                    ];
                    if (! $showScore) $columns = array_values(array_filter($columns, fn ($c) => $c[0] !== 'Minutes after start'));
                    if (! $showIntervalPct) $columns = array_values(array_filter($columns, fn ($c) => $c[0] !== 'Interval %'));
                    $slug = fn ($s) => trim(preg_replace('/[^\p{L}\p{N}]+/u', '-', mb_strtolower((string) $s)), '-') ?: 'x';
                    return [
                        'title' => 'Attendance: ' . $prog['title'] . ' — ' . self::ethiopianDate($f['date']) . ' — taker: ' . $taker,
                        'filename' => 'attendance-' . $slug($prog['title']) . '-' . $f['date'] . '-' . $slug($taker),
                        'range' => null,
                        'period_label' => self::ethiopianDate($f['date']) . ' (' . $f['date'] . ')',
                        'summary' => [
                            ['Program', $prog['title']], ['Date', self::ethiopianDate($f['date'])],
                            ['Scheduled start', $hm($o['starts_at'])], ['Attendance started (official)', $hm($sess['started_at']) . ($sess['start_source'] === 'offline' ? ' (offline, device time)' : '')],
                            ['Ended', $hm($sess['ended_at']) . ($sess['end_reason'] ? ' (' . $sess['end_reason'] . ')' : '')],
                            ['Attendance taker', $taker], ['Total roster', count($roster)], ['Present', $present],
                        ],
                        'tables' => [self::table('Members', $columns, $roster)],
                    ];
                }
                $d = Reports::attendance($f);
                if (isset($d['user_attendance'])) {
                    $s = $d['stats'];
                    return ['title' => 'Attendance report (member)', 'range' => $d['range'],
                        'summary' => array_map(fn ($k) => [ucfirst(str_replace('_', ' ', $k)), $s[$k]], array_keys(array_filter($s, fn ($v) => is_scalar($v) || $v === null))),
                        'tables' => [self::table('Sessions', [['Program', 'title'], ['Date', 'date'], ['Status', 'status']], $d['user_attendance'])]];
                }
                $rows = $d['programs'];
                $sum = fn ($k) => array_sum(array_column($rows, $k));
                return ['title' => 'Attendance report', 'range' => $d['range'],
                    'summary' => [['Sessions', count($rows)], ['Expected', $sum('participants')], ['Present', $sum('attended')], ['Excused', $sum('excused')], ['Absent', $sum('absent')]],
                    'tables' => [self::table('Sessions', [['Program', 'title'], ['Date', 'date'], ['Expected', 'participants'], ['Present', 'attended'], ['Excused', 'excused'], ['Absent', 'absent'], ['Unmarked', 'unmarked'], ['Attendance taker', fn ($r) => $r['takers'] ?? '—']], $rows)]];
            case 'borrowings':
                $d = Reports::borrowings($f);
                $summary = [];
                foreach ((array) $d['by_status'] as $k => $v) $summary[] = ["Borrowings: $k", $v];
                foreach ((array) $d['fines'] as $k => $v) $summary[] = ["Fines $k", $v['total'] . ' (' . $v['count'] . ')'];
                return ['title' => 'Property & borrowing report', 'range' => $d['range'], 'summary' => $summary, 'tables' => [
                    self::table('By item', [['Item', 'name'], ['Code', 'code'], ['Borrowings', 'borrowings'], ['Quantity', 'quantity']], $d['by_item']),
                    self::table('Overdue', [['Member', 'full_name'], ['Item', 'item_name'], ['Quantity', 'quantity'], ['Due', fn ($r) => Dates::toDateOnly($r['due_on'] ?? null)], ['Fine', 'fine_amount']], $d['overdue']),
                ]];
            case 'notifications':
                $d = Reports::notifications($auth, $f);
                return ['title' => 'Notifications report', 'range' => $d['range'], 'summary' => [], 'tables' => [
                    self::table('By type', [['Type', 'type'], ['Delivery', 'delivery_status'], ['Sent', 'count'], ['Read', 'read']], $d['by_type']),
                    self::table('By sender', [['Sender', 'sender_name'], ['Broadcasts', 'broadcasts'], ['Recipients', 'recipients']], $d['by_sender']),
                ]];
            case 'admin-activity':
                $d = Reports::adminActivity($auth, $f);
                return ['title' => 'Administrator activity', 'range' => $d['range'], 'summary' => [['Actions', array_sum(array_column($d['actions'], 'count'))]],
                    'tables' => [self::table('Actions', [['Administrator', 'actor_name'], ['Action', 'action'], ['Count', 'count']], $d['actions'])]];
            case 'audit-logs':
                $rows = self::allPages(fn ($p) => Reports::auditLogs($auth, $f, $p));
                return ['title' => 'Audit log', 'range' => null, 'summary' => [['Entries', count($rows)]],
                    'tables' => [self::table('Entries', [['When', 'created_at'], ['Administrator', 'actor_name'], ['Action', 'action'], ['Record', 'entity_type'], ['Record ID', 'entity_id'], ['Details', 'metadata'], ['IP', 'ip']], $rows)]];
            case 'activity-logs':
                $rows = self::allPages(fn ($p) => Reports::activityLogs($auth, $f, $p));
                return ['title' => 'User activity', 'range' => null, 'summary' => [['Entries', count($rows)]],
                    'tables' => [self::table('Entries', [['When', 'occurred_at'], ['Member', 'user_name'], ['Action', 'action'], ['Subject', 'entity_title'], ['Details', 'metadata']], $rows)]];
            case 'contributions':
                $period = $f['period'] ?? Ethiopian::currentPeriod();
                $rows = self::allPages(fn ($p) => Payments::adminList(['period' => $period] + $f, $p));
                $paid = count(array_filter($rows, fn ($r) => ! empty($r['payment'])));
                return ['title' => 'Monthly contributions', 'range' => null, 'period_label' => $period,
                    'summary' => [['Period (Ethiopian)', $period], ['Members', count($rows)], ['Paid', $paid], ['Unpaid', count($rows) - $paid]],
                    'tables' => [self::table('Members', [['Member', 'full_name'], ['Member ID', fn ($r) => $r['member_id'] ?? $member($r)], ['Type', 'member_type'], ['Status', fn ($r) => empty($r['payment']) ? 'unpaid' : 'paid'], ['Amount', fn ($r) => $r['payment']['amount'] ?? null], ['Paid on', fn ($r) => $r['payment']['paid_on'] ?? null]], $rows)]];
            case 'selection':
                if (empty($f['selection_id'])) throw ApiError::field('selection_id', 'REQUIRED');
                $sel = Selections::get((int) $f['selection_id']);
                $rows = self::allPages(fn ($p) => Selections::results((int) $f['selection_id'], [], $p));
                $q = count(array_filter($rows, fn ($r) => ($r['result'] ?? null) === 'qualified'));
                return ['title' => 'Holiday Mezmur selection: ' . $sel['name'], 'range' => ['from' => $sel['from'], 'to' => $sel['to']], 'summary' => [['Status', $sel['status']], ['Members', count($rows)], ['Qualified', $q]],
                    'tables' => [self::table('Results (alphabetical — not a ranking)', [['Member', 'full_name'], ['Member ID', fn ($r) => $r['member_id'] ?? $member($r)], ['Total', 'total'], ['Result', 'result'], ['Note', fn ($r) => $r['override_reason'] ?? null]], $rows)]];
            case 'projects':
                $d = ProjectReports::summary($auth, $f);
                return ['title' => 'Projects & tasks report', 'range' => null,
                    'summary' => [['Projects', $d['projects']['total']], ['Active projects', $d['projects']['active']], ['Overdue projects', $d['projects']['overdue']], ['Tasks', $d['tasks']['total']], ['Overdue tasks', $d['tasks']['overdue']], ['Budget approved', $d['budget']['approved']], ['Spent', $d['budget']['spent']]],
                    'tables' => [
                        self::table('Projects', [['Project', 'title'], ['Status', 'status'], ['Priority', 'priority'], ['Progress %', 'progress'], ['Deadline', 'deadline'], ['Tasks', fn ($r) => $r['tasks']['total']], ['Completed', fn ($r) => $r['tasks']['completed']], ['Overdue', fn ($r) => $r['tasks']['overdue']], ['Approved budget', fn ($r) => $r['budget']['approved']], ['Spent', fn ($r) => $r['budget']['spent']]], $d['project_list']),
                        self::table('People', [['Member', fn ($r) => $r['user']['full_name'] ?? null], ['Assigned', 'assigned'], ['In progress', 'in_progress'], ['Pending', 'pending'], ['Blocked', 'blocked'], ['Completed', 'completed'], ['Overdue', 'overdue']], $d['users']),
                    ]];
            case 'education':
                $classId = ! empty($f['class_id']) ? (int) $f['class_id'] : null;
                $courseId = ! empty($f['course_id']) ? (int) $f['course_id'] : null;
                $classesQ = DB::table('edu_classes');
                if ($classId) $classesQ->where('id', $classId);
                $classes = $classesQ->get();
                $classIds = $classes->pluck('id')->all();

                $coursesQ = DB::table('edu_courses as c')
                    ->leftJoin('edu_classes as cl', 'cl.id', '=', 'c.class_id')
                    ->leftJoin('users as t', 't.id', '=', 'c.teacher_user_id')
                    ->whereIn('c.class_id', $classIds ?: [0]);
                if ($courseId) $coursesQ->where('c.id', $courseId);
                $courses = $coursesQ->select('c.*', 'cl.name as class_name', 'cl.term', 't.full_name as teacher_name')->get();
                $courseIds = $courses->pluck('id')->all();

                $scoresQ = DB::table('edu_scores as s')
                    ->join('edu_assessments as a', 'a.id', '=', 's.assessment_id')
                    ->join('edu_courses as c', 'c.id', '=', 'a.course_id')
                    ->join('edu_classes as cl', 'cl.id', '=', 'c.class_id')
                    ->join('users as u', 'u.id', '=', 's.user_id')
                    ->leftJoin('users as rec', 'rec.id', '=', 's.recorded_by')
                    ->whereIn('a.course_id', $courseIds ?: [0])
                    ->select('s.*', 'a.title as assessment_title', 'a.max_score', 'a.held_on', 'c.name as course_name', 'cl.name as class_name', 'u.full_name', 'u.member_no', 'u.member_group', 'rec.full_name as recorded_by_name')
                    ->orderBy('cl.name')->orderBy('c.name')->orderBy('u.full_name');
                if (! empty($f['from'])) $scoresQ->where('a.held_on', '>=', Dates::sql($f['from']));
                if (! empty($f['to'])) $scoresQ->where('a.held_on', '<=', Dates::sql($f['to']));
                $scores = $scoresQ->get()->all();

                $summary = [
                    ['Classes', count($classes)],
                    ['Courses', count($courses)],
                    ['Exam & assessment records', count($scores)],
                ];

                $tables = [
                    self::table('Exam & assessment scores', [
                        ['Member', 'full_name'],
                        ['Member ID', fn ($r) => $r['member_id'] ?? $member($r)],
                        ['Class', 'class_name'],
                        ['Course', 'course_name'],
                        ['Assessment', 'assessment_title'],
                        ['Score', fn ($r) => $r['score'] !== null ? Num::round1($r['score']) : '—'],
                        ['Max', fn ($r) => Num::round1($r['max_score'])],
                        ['Held on', fn ($r) => $r['held_on'] ? Dates::toDateOnly($r['held_on']) : '—'],
                        ['Recorded by', fn ($r) => $r['recorded_by_name'] ?? '—'],
                    ], $scores),
                    self::table('Courses and teachers', [
                        ['Class', 'class_name'],
                        ['Course', 'name'],
                        ['Code', 'code'],
                        ['Term', 'term'],
                        ['Teacher', fn ($r) => $r['teacher_name'] ?? '—'],
                    ], $courses->all()),
                ];
                return ['title' => 'Education & exam report', 'range' => null, 'summary' => $summary, 'tables' => $tables];
            case 'education-marks':
                return self::educationMarks($f);
            case 'mezmur-selection':
                return SelectionReports::mezmurExport($auth, $f);
            case 'programs':
                $r = Reports::range($f);
                [$from, $to] = Reports::sqlRange($r);
                $pq = DB::table('programs as p')
                    ->leftJoin('categories as c', 'c.id', '=', 'p.category_id')
                    ->leftJoin('users as cr', 'cr.id', '=', 'p.created_by')
                    ->whereBetween('p.starts_at', [$from, $to])
                    ->select('p.*', 'c.name as category_name', 'cr.full_name as created_by_name')
                    ->orderBy('p.starts_at');
                if (! empty($f['category_id'])) $pq->where('p.category_id', $f['category_id']);
                if (! empty($f['status'])) $pq->where('p.status', $f['status']);
                $programs = $pq->get()->all();

                $byStatus = [];
                foreach ($programs as $p) {
                    $byStatus[$p->status] = ($byStatus[$p->status] ?? 0) + 1;
                }
                $summary = [['Total programs', count($programs)]];
                foreach ($byStatus as $st => $c) $summary[] = ["Status: $st", $c];

                return [
                    'title' => 'Programs report',
                    'range' => ['from' => $r[0], 'to' => $r[1]],
                    'summary' => $summary,
                    'tables' => [
                        self::table('Programs', [
                            ['Program', 'title'],
                            ['Category', 'category_name'],
                            ['Starts at', fn ($r) => Dates::of($r['starts_at'])?->setTimezone(Dates::tz())->format('Y-m-d H:i')],
                            ['Location', 'location'],
                            ['Recurrence', 'recurrence'],
                            ['Status', 'status'],
                            ['Attendance required', fn ($r) => (bool) $r['requires_attendance'] ? 'Yes' : 'No'],
                            ['Audience', 'audience'],
                            ['Created by', fn ($r) => $r['created_by_name'] ?? '—'],
                        ], $programs),
                    ],
                ];
            case 'education-exam':
                return self::examReport($f);
            case 'education-scores':
                return self::educationScores($auth, $f);
            case 'education-activity':
                return self::educationActivity($auth, $f);
            case 'library-inventory':
                return self::libraryInventory($f);
            case 'library-loans':
                return self::libraryLoans($f);
            case 'library-overdue':
                return self::libraryOverdue($f);
        }
        throw ApiError::notFound();
    }

    private static function libraryInventory(array $f): array
    {
        $copies = LibraryCirculation::copies($f, ['limit' => self::MAX_ROWS, 'offset' => 0])['items'];
        $avail = count(array_filter($copies, fn ($c) => $c['status'] === 'available'));
        $onLoan = count(array_filter($copies, fn ($c) => $c['status'] === 'on_loan'));
        $lost = count(array_filter($copies, fn ($c) => $c['status'] === 'lost'));
        $withdrawn = count(array_filter($copies, fn ($c) => $c['status'] === 'withdrawn'));

        $summary = [
            ['Total copies', count($copies)],
            ['Available copies', $avail],
            ['On loan', $onLoan],
            ['Lost copies', $lost],
            ['Withdrawn / Damaged', $withdrawn],
        ];

        $tables = [
            self::table('Library Physical Inventory', [
                ['Copy Code', 'copy_code'],
                ['Book Title', 'book_title'],
                ['Author', 'book_author'],
                ['Category', 'category_name'],
                ['Copy No', 'copy_no'],
                ['Condition', 'condition'],
                ['Location', fn ($r) => $r['location'] ?? '—'],
                ['Status', 'status'],
                ['Borrower', fn ($r) => $r['current_loan']['borrower_name'] ?? '—'],
                ['Due on', fn ($r) => $r['current_loan']['due_on'] ?? '—'],
            ], $copies),
        ];

        return ['title' => 'Sunday-School Library Inventory', 'range' => null, 'summary' => $summary, 'tables' => $tables];
    }

    private static function libraryLoans(array $f): array
    {
        $loans = LibraryCirculation::loans($f, ['limit' => self::MAX_ROWS, 'offset' => 0])['items'];
        $active = count(array_filter($loans, fn ($l) => $l['status'] === 'active'));
        $returned = count(array_filter($loans, fn ($l) => $l['status'] === 'returned'));
