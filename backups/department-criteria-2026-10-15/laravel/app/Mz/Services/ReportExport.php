    }

    public static function ethiopianDate(mixed $d): string
    {
        $dt = Dates::of($d);
        if (! $dt) return '';
        $local = $dt->setTimezone(Dates::tz());
        $e = Ethiopian::toEthiopian((int) $local->format('Y'), (int) $local->format('n'), (int) $local->format('j'));
        return $e['day'] . ' ' . self::ET_MONTHS[$e['month'] - 1] . ' ' . $e['year'] . ' ዓ.ም.';
    }

    private static function cell(mixed $v): string|int|float|null
    {
        if ($v === null) return null;
        if (is_bool($v)) return $v ? '✓' : '—';
        if (is_int($v) || is_float($v)) return $v;
        // Machine-readable in XLSX / CSV (local time); the PDF shows Ethiopian dates.
        if ($v instanceof \DateTimeInterface) return \DateTimeImmutable::createFromInterface($v)->setTimezone(Dates::tz())->format('Y-m-d H:i');
        if (is_array($v) || is_object($v)) return json_encode($v, JSON_UNESCAPED_UNICODE);
        return (string) $v;
    }

    public static function table(string $title, array $columns, iterable $rows): array
    {
        $out = [];
        foreach ($rows as $r) {
            $r = (array) $r;
            $out[] = array_map(fn ($c) => self::cell($c[1] instanceof \Closure ? ($c[1])($r) : ($r[$c[1]] ?? null)), $columns);
            if (count($out) >= self::MAX_ROWS) break;
        }
        return ['title' => $title, 'columns' => array_column($columns, 0), 'rows' => $out];
    }

    private static function allPages(callable $fetch): array
    {
        $items = [];
        for ($page = 1; $page <= 50 && count($items) < self::MAX_ROWS; $page++) {
            $res = $fetch(['page' => $page, 'limit' => 100, 'offset' => ($page - 1) * 100]);
            $items = array_merge($items, $res['items']);
            if ($page >= ($res['meta']['pages'] ?? 1)) break;
        }
        return $items;
    }

    /** The report described once: title, period, summary, tables. */
    public static function build(AuthContext $auth, string $kind, array $f): array
    {
        $member = fn ($r) => MemberIds::format($r['member_no'] ?? null, $r['member_group'] ?? null);
        switch ($kind) {
            case 'users':
                $d = Reports::users($f);
                $summary = [['Distinct sign-ins', $d['distinct_logins']]];
                foreach ((array) $d['by_status'] as $k => $v) $summary[] = ["Accounts: $k", $v];
                return ['title' => 'Users report', 'range' => $d['range'], 'summary' => $summary,
                    'tables' => [self::table('Registrations per day', [['Day', 'day'], ['Registrations', 'count']], $d['registrations_per_day'])]];
            case 'mezmurs':
                $d = Reports::mezmurs($f);
                $t = fn ($title, $rows) => self::table($title, [['Mezmur', 'title'], ['Count', 'count']], $rows);
                return ['title' => 'Mezmur usage report', 'range' => $d['range'], 'summary' => [],
                    'tables' => [$t('Most viewed', $d['top_viewed']), $t('Most played', $d['top_played']), $t('Most favorited', $d['top_favorited']), $t('Most downloaded', $d['top_downloaded']),
                        self::table('Top searches', [['Search', 'q'], ['Count', 'count']], $d['top_searches'])]];
            case 'attendance':
                if (! empty($f['program_id']) && ! empty($f['date'])) {
                    $pid = (int) $f['program_id'];
                    $prog = Programs::get($pid);
                    $roster = self::allPages(fn ($p) => Attendance::roster($pid, ['date' => $f['date']], $p));
                    $present = count(array_filter($roster, fn ($r) => in_array($r['status'] ?? '', ['present', 'late'], true)));
                    return [
                        'title' => 'Attendance roster: ' . $prog['title'],
                        'range' => null,
                        'period_label' => self::ethiopianDate($f['date']) . ' (' . $f['date'] . ')',
                        'summary' => [['Program', $prog['title']], ['Date', self::ethiopianDate($f['date'])], ['Total roster', count($roster)], ['Present / Late', $present]],
                        'tables' => [self::table('Members', [
                            ['Member', 'full_name'],
                            ['Member ID', fn ($r) => $r['member_id'] ?? $member($r)],
                            ['Status', 'status'],
                            ['Attended at', fn ($r) => $r['attended_at'] ? Dates::of($r['attended_at'])?->setTimezone(Dates::tz())->format('H:i') : '—'],
                            ['Via', fn ($r) => $r['via'] ?? '—'],
                            ['Recorded by (Taker)', fn ($r) => $r['recorded_by_name'] ?? '—'],
                            ['Notes', fn ($r) => $r['notes'] ?? '—'],
                        ], $roster)],
                    ];
                }
                $d = Reports::attendance($f);
                if (isset($d['user_attendance'])) {
                    $s = $d['stats'];
                    return ['title' => 'Attendance report (member)', 'range' => $d['range'],
                        'summary' => array_map(fn ($k) => [ucfirst(str_replace('_', ' ', $k)), $s[$k]], array_keys(array_filter($s, fn ($v) => is_scalar($v) || $v === null))),
                        'tables' => [self::table('Sessions', [['Program', 'title'], ['Date', 'date'], ['Status', 'status']], $d['user_attendance'])]];
                }
                $rows = $d['programs'];
                $sum = fn ($k) => array_sum(array_column($rows, $k));
                return ['title' => 'Attendance report', 'range' => $d['range'],
                    'summary' => [['Sessions', count($rows)], ['Expected', $sum('participants')], ['Present', $sum('attended')], ['Late', $sum('late')], ['Excused', $sum('excused')], ['Absent', $sum('absent')]],
                    'tables' => [self::table('Sessions', [['Program', 'title'], ['Date', 'date'], ['Expected', 'participants'], ['Present', 'attended'], ['Late', 'late'], ['Excused', 'excused'], ['Absent', 'absent'], ['Unmarked', 'unmarked'], ['Assigned takers', fn ($r) => $r['takers'] ?? '—']], $rows)]];
            case 'borrowings':
                $d = Reports::borrowings($f);
                $summary = [];
                foreach ((array) $d['by_status'] as $k => $v) $summary[] = ["Borrowings: $k", $v];
                foreach ((array) $d['fines'] as $k => $v) $summary[] = ["Fines $k", $v['total'] . ' (' . $v['count'] . ')'];
                return ['title' => 'Property & borrowing report', 'range' => $d['range'], 'summary' => $summary, 'tables' => [
                    self::table('By item', [['Item', 'name'], ['Code', 'code'], ['Borrowings', 'borrowings'], ['Quantity', 'quantity']], $d['by_item']),
                    self::table('Overdue', [['Member', 'full_name'], ['Item', 'item_name'], ['Quantity', 'quantity'], ['Due', fn ($r) => Dates::toDateOnly($r['due_on'] ?? null)], ['Fine', 'fine_amount']], $d['overdue']),
                ]];
            case 'notifications':
                $d = Reports::notifications($auth, $f);
                return ['title' => 'Notifications report', 'range' => $d['range'], 'summary' => [], 'tables' => [
                    self::table('By type', [['Type', 'type'], ['Delivery', 'delivery_status'], ['Sent', 'count'], ['Read', 'read']], $d['by_type']),
                    self::table('By sender', [['Sender', 'sender_name'], ['Broadcasts', 'broadcasts'], ['Recipients', 'recipients']], $d['by_sender']),
                ]];
            case 'admin-activity':
                $d = Reports::adminActivity($auth, $f);
                return ['title' => 'Administrator activity', 'range' => $d['range'], 'summary' => [['Actions', array_sum(array_column($d['actions'], 'count'))]],
                    'tables' => [self::table('Actions', [['Administrator', 'actor_name'], ['Action', 'action'], ['Count', 'count']], $d['actions'])]];
            case 'audit-logs':
                $rows = self::allPages(fn ($p) => Reports::auditLogs($auth, $f, $p));
                return ['title' => 'Audit log', 'range' => null, 'summary' => [['Entries', count($rows)]],
                    'tables' => [self::table('Entries', [['When', 'created_at'], ['Administrator', 'actor_name'], ['Action', 'action'], ['Record', 'entity_type'], ['Record ID', 'entity_id'], ['Details', 'metadata'], ['IP', 'ip']], $rows)]];
            case 'activity-logs':
                $rows = self::allPages(fn ($p) => Reports::activityLogs($auth, $f, $p));
                return ['title' => 'User activity', 'range' => null, 'summary' => [['Entries', count($rows)]],
                    'tables' => [self::table('Entries', [['When', 'occurred_at'], ['Member', 'user_name'], ['Action', 'action'], ['Subject', 'entity_title'], ['Details', 'metadata']], $rows)]];
            case 'contributions':
                $period = $f['period'] ?? Ethiopian::currentPeriod();
                $rows = self::allPages(fn ($p) => Payments::adminList(['period' => $period] + $f, $p));
                $paid = count(array_filter($rows, fn ($r) => ! empty($r['payment'])));
                return ['title' => 'Monthly contributions', 'range' => null, 'period_label' => $period,
                    'summary' => [['Period (Ethiopian)', $period], ['Members', count($rows)], ['Paid', $paid], ['Unpaid', count($rows) - $paid]],
                    'tables' => [self::table('Members', [['Member', 'full_name'], ['Member ID', fn ($r) => $r['member_id'] ?? $member($r)], ['Type', 'member_type'], ['Status', fn ($r) => empty($r['payment']) ? 'unpaid' : 'paid'], ['Amount', fn ($r) => $r['payment']['amount'] ?? null], ['Paid on', fn ($r) => $r['payment']['paid_on'] ?? null]], $rows)]];
            case 'selection':
                if (empty($f['selection_id'])) throw ApiError::field('selection_id', 'REQUIRED');
