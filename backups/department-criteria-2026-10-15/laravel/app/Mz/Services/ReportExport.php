/**
 * One reusable export template for every report: a report is described once as a title, its
 * period, the filters applied, a summary (label → value) and detail tables; it is then rendered as
 *  - PDF: print-ready A4 with logo, title, Ethiopian date, period, generated by / at, filters,
 *    summary, tables, header / footer, page numbers and a reference id (Amharic via Noto Sans Ethiopic);
 *  - XLSX: a Summary sheet + one sheet per table, frozen header rows, sized columns;
 *  - CSV: the main table only, plain and machine-readable (UTF-8 with BOM for Excel).
 * Every export is audited (kind, format, filters, reference) — never a raw database dump.
 */
